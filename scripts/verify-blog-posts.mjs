// Blog migrasyonu FAZ B doğrulama script'i — 618 yazının tamamı toplu
// işlendikten sonra ADIM 1/FAZ A'da bulunan sorun kalıplarının (boş/
// anlamsız excerpt, kalıntı H1, bozuk alt metni, kategori tekrarı) başka
// yazılarda da olup olmadığını tarar + tüm sayfaların/görsellerin canlı
// olduğunu doğrular (bkz. CLAUDE.md "Blog migrasyonu").
//
// Önkoşul: dev server ayakta olmalı (`astro dev --background`) — sayfa
// HTTP kontrolleri için, projedeki diğer `test-*.mjs` script'leriyle aynı
// desen.
// Çalıştırma: node scripts/verify-blog-posts.mjs

import { readFileSync } from 'node:fs';

const BASE_URL = 'http://localhost:4321';
const CONCURRENCY = 20;
const MIN_EXCERPT_LENGTH = 40;

const posts = JSON.parse(readFileSync('src/content/blog/posts.json', 'utf-8'));

async function mapLimit(items, limit, fn) {
  const results = new Array(items.length);
  let index = 0;
  async function worker() {
    while (index < items.length) {
      const current = index++;
      results[current] = await fn(items[current], current);
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return results;
}

function looksAutoGeneratedFromFilename(altText, sourceUrl) {
  const filename = sourceUrl.split('/').pop()?.replace(/\.[a-z0-9]+$/i, '') ?? '';
  const normalize = (s) => s.toLowerCase().replace(/[-_]+/g, ' ').replace(/\s+/g, ' ').trim();
  return normalize(altText) === normalize(filename);
}

console.log(`src/content/blog/posts.json içinde ${posts.length} yazı bulundu.\n`);

// --- 1) Sayfa HTTP durumu ----------------------------------------------------
console.log('--- 1) Sayfa HTTP durumu (/blog/<slug>/) ---');
const pageResults = await mapLimit(posts, CONCURRENCY, async (post) => {
  try {
    const res = await fetch(`${BASE_URL}/blog/${post.slug}/`);
    return { slug: post.slug, status: res.status };
  } catch (e) {
    return { slug: post.slug, status: 'ERROR', error: e.message };
  }
});
const brokenPages = pageResults.filter((r) => r.status !== 200);
console.log(`${posts.length - brokenPages.length}/${posts.length} sayfa 200 döndü.`);
brokenPages.forEach((r) => console.log(`  ❌ /blog/${r.slug}/ → ${r.status}${r.error ? ` (${r.error})` : ''}`));

// --- 2) Öne çıkan görseller ---------------------------------------------------
console.log('\n--- 2) Öne çıkan görseller (canlı idenfit.com) ---');
const postsWithImages = posts.filter((p) => p.featuredImage);
const imageResults = await mapLimit(postsWithImages, CONCURRENCY, async (post) => {
  try {
    const res = await fetch(post.featuredImage.url, { method: 'HEAD' });
    return { slug: post.slug, url: post.featuredImage.url, status: res.status };
  } catch (e) {
    return { slug: post.slug, url: post.featuredImage.url, status: 'ERROR', error: e.message };
  }
});
const brokenImages = imageResults.filter((r) => r.status !== 200);
console.log(
  `${postsWithImages.length - brokenImages.length}/${postsWithImages.length} görsel 200 döndü ` +
    `(${posts.length - postsWithImages.length} yazının görseli yok — kontrol dışı, bkz. bulgu #4 aşağıda).`,
);
brokenImages.forEach((r) => console.log(`  ❌ ${r.slug} → ${r.url} (${r.status}${r.error ? `, ${r.error}` : ''})`));

// --- 3) Excerpt kalitesi -----------------------------------------------------
console.log('\n--- 3) Excerpt kalitesi ---');
const badExcerpts = posts.filter((p) => !p.excerpt || p.excerpt.trim().length < MIN_EXCERPT_LENGTH);
console.log(`${posts.length - badExcerpts.length}/${posts.length} yazının excerpt'i yeterli uzunlukta (>=${MIN_EXCERPT_LENGTH} karakter).`);
badExcerpts.forEach((p) => console.log(`  ⚠ ${p.slug} → "${p.excerpt}"`));

// --- 4) Kalıntı H1 taraması ---------------------------------------------------
console.log('\n--- 4) Gövdede kalıntı <h1> taraması ---');
const postsWithH1 = posts.filter((p) => /<h1[\s>]/i.test(p.content));
console.log(`${posts.length - postsWithH1.length}/${posts.length} yazının gövdesinde H1 yok (beklenen — şablon kendi H1'ini basıyor).`);
postsWithH1.forEach((p) => console.log(`  ⚠ ${p.slug}`));

// --- 5) Alt metni kalitesi -----------------------------------------------------
console.log('\n--- 5) Öne çıkan görsel + alt metni durumu ---');
const postsWithoutImage = posts.filter((p) => !p.featuredImage);
const badAlts = postsWithImages.filter(
  (p) => !p.featuredImage.alt?.trim() || looksAutoGeneratedFromFilename(p.featuredImage.alt, p.featuredImage.url),
);
console.log(`${postsWithImages.length - badAlts.length}/${postsWithImages.length} görselin alt metni sağlıklı.`);
console.log(`${postsWithoutImage.length} yazının hiç görseli yok (kaynakta da yok — bkz. CLAUDE.md).`);
postsWithoutImage.forEach((p) => console.log(`  ℹ ${p.slug} — görsel yok (kaynakta da yok)`));
badAlts.forEach((p) => console.log(`  ⚠ ${p.slug} → alt="${p.featuredImage.alt}"`));

// --- 6) Kategori tekrarı taraması ---------------------------------------------
console.log('\n--- 6) Kategori tekrarı taraması (aynı isim aynı yazıda 2+ kez) ---');
const dupeCategoryPosts = posts.filter((p) => {
  const names = p.categories.map((c) => c.name);
  return new Set(names).size !== names.length;
});
console.log(`${posts.length - dupeCategoryPosts.length}/${posts.length} yazıda kategori tekrarı yok.`);
dupeCategoryPosts.forEach((p) => console.log(`  ❌ ${p.slug} → ${JSON.stringify(p.categories.map((c) => c.name))}`));

// --- Özet ---------------------------------------------------------------------
console.log('\n=== ÖZET ===');
console.log(`Toplam yazı: ${posts.length}`);
console.log(`1) Kırık sayfa: ${brokenPages.length}`);
console.log(`2) Kırık görsel: ${brokenImages.length}`);
console.log(`3) Zayıf excerpt (<${MIN_EXCERPT_LENGTH} karakter): ${badExcerpts.length}`);
console.log(`4) Kalıntı H1: ${postsWithH1.length}`);
console.log(`5) Zayıf/eksik alt metni: ${badAlts.length} (+ ${postsWithoutImage.length} görselsiz yazı, bilgi amaçlı)`);
console.log(`6) Kategori tekrarı: ${dupeCategoryPosts.length}`);

// Kırık sayfa/görsel/kategori-tekrarı GERÇEK regresyon — build'i/CI'ı
// kırmalı. Zayıf excerpt/alt metni bu script'in bulabileceği ama otomatik
// düzeltemeyeceği (editoryal karar gerektirebilir) bulgular — bilgi amaçlı,
// exit code'u etkilemiyor.
const hardFailures = brokenPages.length + brokenImages.length + dupeCategoryPosts.length;
process.exit(hardFailures > 0 ? 1 : 0);
